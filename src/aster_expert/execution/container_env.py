"""Shared mechanism to run a Python script inside the Aster container.

See docs/architecture.md, ADR-002, mechanism (c): locate `run_aster` without
assuming a hash-bearing install prefix, resolve its prefix, source
`share/aster/profile.sh` (`set -u` lifted only around that one `source`, an
upstream file that is not nounset-safe), and add the Spack view's
site-packages — derived from the resolved prefix, never a hardcoded path —
to `PYTHONPATH` beforehand (assumed deviation from the official mechanism,
needed for `numpy`).

**`LD_LIBRARY_PATH` amendment (lot 11, docs/architecture.md ADR-002).**
Lots 2/4/10 never import `libaster` (catalogue introspection and
`checkCommandSyntax` are pure Python + `numpy`), so the Spack view's shared
libraries were never needed on `LD_LIBRARY_PATH` before this lot. A real
execution does import it (`code_aster.Utilities.ExecutionParameter` ->
`import libaster`), and that failed in session with `ImportError:
libmed.so.11: cannot open shared object file` — `share/aster/profile.sh`
alone sets `LD_LIBRARY_PATH` for the Aster install's own bundled libraries,
never for third-party ones the Spack packaging of this image supplies
externally (the same class of gap `PYTHONPATH_EXTRA` above already works
around for `numpy`; confirmed by locating `libmed.so.11` directly under the
resolved `$VIEW/lib`, nowhere under the Aster install prefix itself).
`LD_LIBRARY_PATH_EXTRA` is exported *before* sourcing `profile.sh`, exactly
like `PYTHONPATH_EXTRA`, so profile.sh's own append (it reads the prior
value, per the `set -u` note below) preserves it rather than clobbering it.

Callers append their own ``python3 <script> <args>`` invocation line after
this setup: lot 2's probe interpolates shell variables computed by the setup
itself (``$RA``, ``$PYTHONPATH_EXTRA``); lot 4's extractor passes static,
host-provided argument values instead. Keeping the setup shared avoids
re-deriving (and risking drift in) this mechanism per lot.
"""

from __future__ import annotations

MOUNT_TARGET = "/work"

# Locates `run_aster` without assuming any hash-bearing install prefix.
# `-xdev` keeps the search on the container's own filesystem layer.
_FIND_RUN_ASTER = (
    "find / -xdev -maxdepth 14 -type f -name run_aster 2>/dev/null | head -1"
)

# `set -u` is on for the whole setup: a typo here must not run silently with
# an empty variable. It is only lifted around sourcing
# `share/aster/profile.sh`, generated by the code_aster build (not by this
# project), which expands `${ASTER_PROFILE_LOADED}` and `${LD_LIBRARY_PATH}`
# without a default and is not `nounset`-safe. Verified in session: `set -u`
# around the whole script makes it fail with "ASTER_PROFILE_LOADED: unbound
# variable" before profile.sh can set anything; disarming the whole script
# to work around one upstream file would be too broad a fix.
_ENVIRONMENT_SETUP_TEMPLATE = """\
set -u
RA=$({find_run_aster})
if [ -z "$RA" ]; then
    echo "run_aster not found in image" >&2
    exit 3
fi
PREFIX=$(dirname "$(dirname "$(readlink -f "$RA")")")
export RUNASTER_ROOT="$PREFIX"

# The Spack view supplies third-party dependencies of the `Cata` package
# (numpy) that `share/aster/profile.sh` alone does not provide (ADR-002,
# assumed deviation from the official mechanism). Its root is derived from
# the resolved $PREFIX by walking up its own ancestry, never from a
# hardcoded path: only the install prefix is guaranteed to exist, and the
# Spack root above it is not at a fixed depth across images.
SPACK_ROOT=""
CANDIDATE="$PREFIX"
while [ -n "$CANDIDATE" ] && [ "$CANDIDATE" != "/" ] && [ -z "$SPACK_ROOT" ]; do
    if [ -d "$CANDIDATE/var/spack/environments" ]; then
        SPACK_ROOT="$CANDIDATE"
    fi
    CANDIDATE=$(dirname "$CANDIDATE")
done

VIEW=""
if [ -n "$SPACK_ROOT" ]; then
    VIEW=$(find -L "$SPACK_ROOT/var/spack/environments" -maxdepth 3 \\
        -type d -name view 2>/dev/null | head -1)
fi

PYTHONPATH_EXTRA=""
LD_LIBRARY_PATH_EXTRA=""
if [ -n "$VIEW" ]; then
    PYVER_DIR=$(find "$VIEW/lib" -maxdepth 1 -type d -name 'python3.*' 2>/dev/null \\
        | head -1)
    PYVER=$(basename "$PYVER_DIR")
    if [ -n "$PYVER" ] && [ -d "$VIEW/lib/$PYVER/site-packages" ]; then
        PYTHONPATH_EXTRA="$VIEW/lib/$PYVER/site-packages"
    fi
    if [ -d "$VIEW/lib" ]; then
        LD_LIBRARY_PATH_EXTRA="$VIEW/lib"
    fi
    if [ -d "$VIEW/lib64" ]; then
        LD_LIBRARY_PATH_EXTRA="$LD_LIBRARY_PATH_EXTRA:$VIEW/lib64"
    fi
fi
export PYTHONPATH="$PYTHONPATH_EXTRA"
export LD_LIBRARY_PATH="$LD_LIBRARY_PATH_EXTRA"

set +u
# shellcheck disable=SC1091
source "$PREFIX/share/aster/profile.sh"
set -u

# Lot 47 quater: `run_aster` restarts itself under `mpiexec` when `mpi_nbcpu` > 1
# (its configuration: "mpiexec -n {{mpi_nbcpu}} --tag-output {{program}}"). In
# simvia/code_aster:17.4.0, `mpiexec` (OpenMPI 5.0.8) is only in the Spack view's
# `bin`, which neither the image's PATH nor profile.sh provides: appended last, so
# that the Python chosen by profile.sh stays first.
if [ -n "$VIEW" ] && [ -d "$VIEW/bin" ]; then
    export PATH="$PATH:$VIEW/bin"
fi
"""


def build_environment_setup_script() -> str:
    """Bash snippet resolving and activating the Aster Python environment.

    Does not include a trailing `python3 ...` invocation: append one,
    referencing `$RA`/`$PYTHONPATH_EXTRA` if needed, or `MOUNT_TARGET` for a
    script copied into the container's mounted work directory.
    """
    return _ENVIRONMENT_SETUP_TEMPLATE.format(find_run_aster=_FIND_RUN_ASTER)
