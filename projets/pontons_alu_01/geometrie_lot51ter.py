"""Geometry of PONTONS-ALU-01, lot 51 ter: the whole pontoon, from the parameters of
`maillage/maillage_ponton_51ter.py`.

As in lots 51 and 51 bis, the parameters are written once, at the top of the Salome
script, and read here without running it; a variant changes the stations of the piers,
the free heights of their piles, the end cantilever and the purlin size through the
parameter file. This module rebuilds, independently of the script, what the trunk and
the generator need (members and their discretisation, links, node and load groups, the
footing grids, the expected counts of `mesh check`, the influence widths of the surface
loads). What changes from lot 51 bis (decisions P53 to P58):

- AVP levels (P53): top of the main beams and purlins +1,40 (main beam axis +1,30,
  purlin axis +1,40 − side/2), pin axis +1,16 (P54), top of the ring +1,09, ring
  0,40 × 0,40 (soffit +0,69 = pile heads);
- the whole pontoon (P58): span T1 from the abutment (X = 0) to pier P1, then for each
  pier Pk its small span PTk between its two cap beams and the long span T(k+1) to the
  next pier; after P5, PT5 goes on without splice into the end cantilever PF, closed
  by a transverse edge purlin (« panne de rive »);
- one pier per station, generated by a loop: pins on both cap beams (P54: on C2 of P5,
  one ear only, the beam being continuous), ring, four piles fixed at both ends, one
  footing per pier at its own level;
- the abutment (X = 0) is the only longitudinal fixed point; the fixed support at
  X = 14,02 of lot 51 bis is gone;
- the ring corners: each tie is split at the face of the cap beams, so that the pieces
  inside a cap beam (group ANGLES_ANNEAU) carry no weight and no buoyancy (correction of
  lot 51 ter: the corners were counted twice).
"""

from __future__ import annotations

import ast
import json
